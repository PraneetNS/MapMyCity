#!/usr/bin/env python3
"""
scripts/import_shapefile_wards.py
=================================
Administrative ward boundaries ingestion and PostGIS spatial indexing script.
Parses GeoJSON/GIS ward boundary definitions, validates polygon topology,
and generates spatial loading statements for municipal zoning.
"""

import sys
import os
import json
import argparse
from typing import Dict, Any, List


