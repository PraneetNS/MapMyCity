def parse_and_validate_wards(data: Dict[str, Any], city: str = "Bengaluru") -> List[Dict[str, Any]]:
    features = data.get("features", [])
    valid_wards = []

    for idx, feat in enumerate(features):
        props = feat.get("properties", {})
        geom = feat.get("geometry", {})
        ward_id = props.get("ward_id") or f"WARD-{idx+1:03d}"
        ward_name = props.get("ward_name") or f"Ward {ward_id}"
        geom_type = geom.get("type")

        if geom_type not in ["Polygon", "MultiPolygon"]:
            continue

        coords = geom.get("coordinates", [])
        if not coords:
            continue

        valid_wards.append({
            "ward_id": ward_id,
            "ward_name": ward_name,
            "city": city,
            "zone": props.get("zone", "General"),
            "population": props.get("population", 0),
            "geometry": geom
        })

    return valid_wards


def generate_postgis_sql(wards: List[Dict[str, Any]]) -> str:
    lines = [
        "-- Auto-generated by import_shapefile_wards.py",
        "BEGIN;",
        "CREATE TABLE IF NOT EXISTS municipal_wards (",
        "    id SERIAL PRIMARY KEY,",
        "    ward_id VARCHAR(64) UNIQUE NOT NULL,",
        "    ward_name VARCHAR(128) NOT NULL,",
        "    city VARCHAR(64) NOT NULL,",
        "    zone VARCHAR(64),",
        "    population INT DEFAULT 0,",
        "    geom GEOMETRY(Geometry, 4326) NOT NULL,",
        "    created_at TIMESTAMPTZ DEFAULT NOW()",
        ");",
        "CREATE INDEX IF NOT EXISTS idx_municipal_wards_geom ON municipal_wards USING GIST(geom);",
        ""
    ]

    for w in wards:
        geom_json = json.dumps(w["geometry"])
        sql = (
            f"INSERT INTO municipal_wards (ward_id, ward_name, city, zone, population, geom) "
            f"VALUES ('{w['ward_id']}', '{w['ward_name']}', '{w['city']}', '{w['zone']}', {w['population']}, "
            f"ST_SetSRID(ST_GeomFromGeoJSON('{geom_json}'), 4326)) "
            f"ON CONFLICT (ward_id) DO UPDATE SET ward_name = EXCLUDED.ward_name, geom = EXCLUDED.geom;"
        )
        lines.append(sql)

    lines.append("COMMIT;")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Ingest administrative ward boundaries into PostGIS")
    parser.add_argument("--file", "-f", help="Path to input GeoJSON file containing ward boundaries")
    parser.add_argument("--city", "-c", default="Bengaluru", help="City name association")
    parser.add_argument("--output-sql", "-o", help="Path to write PostGIS SQL script")
    parser.add_argument("--dry-run", action="store_true", help="Validate without outputting SQL file")
    args = parser.parse_args()

    if args.file and os.path.exists(args.file):
        with open(args.file, "r", encoding="utf-8") as f:
            data = json.load(f)
    else:
        print("[INFO] No file provided or file not found; using built-in reference ward boundaries.")
        data = generate_sample_ward_geojson()

    wards = parse_and_validate_wards(data, city=args.city)
    print(f"[INFO] Successfully validated {len(wards)} municipal wards for city '{args.city}'.")

    sql_output = generate_postgis_sql(wards)

    if args.output_sql:
        with open(args.output_sql, "w", encoding="utf-8") as f:
            f.write(sql_output)
        print(f"[SUCCESS] Wrote PostGIS loader statements to {args.output_sql}")
    elif not args.dry_run:
        print("\n--- Generated SQL Preview ---")
        print(sql_output[:400] + "\n... [truncated] ...\nCOMMIT;")


if __name__ == "__main__":
    main()
